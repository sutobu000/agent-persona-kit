#!/usr/bin/env node
/**
 * persona-kit generator.
 *
 * Reads the shared persona/memory templates in `core/` plus a config file
 * (`kit.config.json`) and emits one instruction file per supported tool:
 *
 *   out/CLAUDE.md                 Claude Code       (docs: <200 lines per file)
 *   out/AGENTS.md                 OpenAI Codex      (docs: 32 KiB combined budget)
 *   out/copilot-instructions.md   GitHub Copilot    (docs: "no longer than 2 pages")
 *
 * Zero dependencies: Node >= 18, standard library only.
 *
 * Template syntax (see core/*.md):
 *   <!-- @section id=<id> targets=claude,codex,copilot -->  ... <!-- @end -->
 *     The block is emitted only for the listed targets.
 *   [detail] <line>
 *     Kept (marker stripped) for claude/codex; dropped for copilot, which the
 *     GitHub docs ask to keep short and non-task-specific.
 *   {{PLACEHOLDER}}
 *     Replaced by the same-named key in the config. An unresolved placeholder
 *     is a hard error, so a half-filled profile can never ship.
 *
 * Usage: node build/generate.mjs [configPath] [outDir]
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CORE_DIR = join(ROOT, "core");

/** Order matters: persona first, then memory operations. */
const CORE_FILES = ["persona-core.md", "memory-rules.md"];

/**
 * Per-target output shape. `budget` values come from each vendor's published
 * guidance (see README.md for the sources and the date they were checked);
 * they are advisory, so exceeding one warns rather than fails.
 */
const TARGETS = {
  claude: {
    file: "CLAUDE.md",
    label: "Claude Code",
    budget: { kind: "lines", limit: 200, note: "docs guidance: keep each CLAUDE.md under 200 lines" },
    header: (c) => [
      `# ${c.NAME} — ${c.SCOPE_LABEL}プロファイル`,
      "",
      "<!-- Generated by persona-kit (build/generate.mjs). Edit core/*.md and kit.config.json, not this file. -->",
      "",
      `このファイルは常時ロードされる。${c.SCOPE_LABEL}の作業でのみ使う。`,
    ],
    footer: () => [
      "",
      "## 置き場所",
      "",
      "- 個人設定: `~/.claude/CLAUDE.md`",
      "- リポジトリ共有: `./CLAUDE.md`(コミットする)",
      "- 組織配布: managed policy の `CLAUDE.md`、または `managed-settings.json` の `claudeMd` キー",
      "- リポ固有のルールが増えたら `.claude/rules/*.md` へ切り出す(該当ファイルを触ったときだけ読まれる)。",
    ],
  },
  codex: {
    file: "AGENTS.md",
    label: "OpenAI Codex",
    budget: {
      kind: "bytes",
      limit: 32 * 1024,
      note: "config default project_doc_max_bytes = 32 KiB, shared across all AGENTS.md",
    },
    header: (c) => [
      `# ${c.NAME} — ${c.SCOPE_LABEL}プロファイル`,
      "",
      "<!-- Generated by persona-kit (build/generate.mjs). Edit core/*.md and kit.config.json, not this file. -->",
      "",
      `このファイルは AGENTS.md 標準の指示ファイル。${c.SCOPE_LABEL}の作業でのみ使う。`,
    ],
    footer: () => [
      "",
      "## 置き場所",
      "",
      "- 個人設定: `~/.codex/AGENTS.md`",
      "- リポジトリ: ルートの `AGENTS.md`(サブディレクトリにも置ける)",
      "- ルートから作業ディレクトリまでの各 `AGENTS.md` が連結され、下位(作業ディレクトリに近い方)が後に来て優先する。",
      "- 合計サイズは `~/.codex/config.toml` の `project_doc_max_bytes`(既定32KiB)で打ち切られる。長くしすぎない。",
    ],
  },
  copilot: {
    file: "copilot-instructions.md",
    label: "GitHub Copilot",
    budget: { kind: "lines", limit: 120, note: 'docs guidance: "no longer than 2 pages", not task specific' },
    header: (c) => [
      `# ${c.NAME} — ${c.SCOPE_LABEL}プロファイル`,
      "",
      "<!-- Generated by persona-kit (build/generate.mjs). Edit core/*.md and kit.config.json, not this file. -->",
    ],
    footer: () => [
      "",
      "## 置き場所",
      "",
      "- リポジトリ全体: `.github/copilot-instructions.md`",
      "- パス別: `.github/instructions/<name>.instructions.md`(frontmatter の `applyTo` グロブが必須)",
      "- 優先順位は 個人 > リポジトリ > 組織。組織レベルは organization owner だけが設定できる。",
    ],
  },
};

function fail(message) {
  console.error(`ERROR: ${message}`);
  process.exit(1);
}

function loadConfig(path) {
  let raw;
  try {
    raw = readFileSync(path, "utf8");
  } catch {
    fail(`config not found: ${path}`);
  }
  try {
    return JSON.parse(raw);
  } catch (error) {
    fail(`config is not valid JSON (${path}): ${error.message}`);
  }
}

const SECTION_OPEN = /^<!--\s*@section\s+id=(\S+)\s+targets=(\S+)\s*-->\s*$/;
const SECTION_CLOSE = /^<!--\s*@end\s*-->\s*$/;
const DETAIL_PREFIX = "[detail]";

/**
 * Splits one core template into `{ id, targets, lines }` blocks. Text outside a
 * section marker is ignored on purpose: that is where a template keeps its own
 * authoring notes, which must never reach a generated file.
 */
function parseSections(text, sourceName) {
  const sections = [];
  let current = null;
  text.split(/\r?\n/).forEach((line, index) => {
    const open = SECTION_OPEN.exec(line);
    if (open) {
      if (current) fail(`${sourceName}:${index + 1}: nested @section (id=${open[1]})`);
      current = { id: open[1], targets: open[2].split(","), lines: [] };
      return;
    }
    if (SECTION_CLOSE.test(line)) {
      if (!current) fail(`${sourceName}:${index + 1}: @end without @section`);
      sections.push(current);
      current = null;
      return;
    }
    if (current) current.lines.push(line);
  });
  if (current) fail(`${sourceName}: unclosed @section (id=${current.id})`);
  return sections;
}

/** Applies the `[detail]` line filter for one target. */
function filterDetail(lines, keepDetail) {
  const out = [];
  for (const line of lines) {
    const trimmed = line.trimStart();
    if (!trimmed.startsWith(DETAIL_PREFIX)) {
      out.push(line);
      continue;
    }
    if (!keepDetail) continue;
    const indent = line.slice(0, line.length - trimmed.length);
    out.push(indent + trimmed.slice(DETAIL_PREFIX.length).trimStart());
  }
  return out;
}

/** Collapses the blank-line runs that section filtering leaves behind. */
function tidy(lines) {
  const out = [];
  for (const line of lines) {
    if (line.trim() === "" && out.length > 0 && out[out.length - 1].trim() === "") continue;
    out.push(line);
  }
  while (out.length > 0 && out[0].trim() === "") out.shift();
  while (out.length > 0 && out[out.length - 1].trim() === "") out.pop();
  return out;
}

function substitute(text, config, targetKey) {
  const unresolved = new Set();
  const filled = text.replace(/\{\{([A-Z0-9_]+)\}\}/g, (match, key) => {
    const value = config[key];
    if (typeof value !== "string" || value.length === 0) {
      unresolved.add(key);
      return match;
    }
    return value;
  });
  if (unresolved.size > 0) {
    fail(`[${targetKey}] unresolved placeholders in config: ${[...unresolved].sort().join(", ")}`);
  }
  return filled;
}

function build(targetKey, sections, config) {
  const target = TARGETS[targetKey];
  const keepDetail = targetKey !== "copilot";
  const body = [];
  for (const section of sections) {
    if (!section.targets.includes(targetKey)) continue;
    body.push(...filterDetail(section.lines, keepDetail), "");
  }
  const lines = [...target.header(config), "", ...tidy(body), ...target.footer(), ""];
  return substitute(lines.join("\n"), config, targetKey);
}

function checkBudget(targetKey, text) {
  const { budget, label } = TARGETS[targetKey];
  const actual = budget.kind === "lines" ? text.split("\n").length : Buffer.byteLength(text, "utf8");
  const unit = budget.kind === "lines" ? "lines" : "bytes";
  const over = actual > budget.limit;
  if (over) console.warn(`  WARN [${label}] ${actual} ${unit} > ${budget.limit} — ${budget.note}`);
  return `${actual} ${unit} / ${budget.limit} (${over ? "OVER" : "ok"})`;
}

function main() {
  const configPath = resolve(process.argv[2] ?? join(ROOT, "kit.config.json"));
  const outDir = resolve(process.argv[3] ?? join(ROOT, "out"));
  const config = loadConfig(configPath);

  const available = new Set(readdirSync(CORE_DIR));
  const sections = [];
  for (const name of CORE_FILES) {
    if (!available.has(name)) fail(`missing core template: core/${name}`);
    sections.push(...parseSections(readFileSync(join(CORE_DIR, name), "utf8"), `core/${name}`));
  }
  if (sections.length === 0) fail("no @section blocks found in core/");

  mkdirSync(outDir, { recursive: true });
  console.log(`persona-kit: config=${configPath}`);
  console.log(`persona-kit: ${sections.length} sections -> ${outDir}`);

  for (const [key, target] of Object.entries(TARGETS)) {
    const setting = config.targets?.[key];
    if (setting && setting.enabled === false) {
      console.log(`  skip ${target.label}`);
      continue;
    }
    const fileName = setting?.file ?? target.file;
    const text = build(key, sections, config);
    writeFileSync(join(outDir, fileName), text, "utf8");
    console.log(`  wrote ${fileName.padEnd(26)} ${checkBudget(key, text)}`);
  }
}

main();
